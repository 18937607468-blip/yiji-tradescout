import type { Evidence } from "./types";

export type DiscoveryCategory = "brake_lining" | "disc_brake_pad" | "brake_shoe";
export type DiscoveryRole = "importer" | "distributor" | "wholesaler";
export type DiscoveryCriteria = {
  productId: string;
  category: DiscoveryCategory;
  targetMarket: string;
  buyerRoles: DiscoveryRole[];
  extraTerms: string;
  excludedTerms: string;
  hsCode?: string;
  hsCategoryConfirmed?: boolean;
};
export type DiscoveryHsOption = { category: DiscoveryCategory | "clutch_facing"; label: string; english: string; companyCode: string; supported: boolean; sourceUrl: string };
export type DiscoveryHsAssessment = {
  rawCode: string;
  normalizedCode: string;
  hs6: string;
  formatValid: boolean;
  matchLevel: "empty" | "company_code" | "company_prefix" | "hs6" | "unknown";
  ambiguous: boolean;
  options: DiscoveryHsOption[];
  warnings: string[];
};
export type DiscoveryCustomsHint = {
  id: string;
  sourceName: string;
  sourceRow: number | null;
  hsCode: string;
  description: string;
  country: string;
  dataClass: "real" | "synthetic";
  hsAssessment: DiscoveryHsAssessment;
};
export type DiscoveryPlan = {
  seedCompanyId: string;
  seedName: string;
  criteria: DiscoveryCriteria;
  queries: string[];
  planHash: string;
  seedHints: string[];
  customsHints: DiscoveryCustomsHint[];
  customsHintCount: number;
  hsAssessment: DiscoveryHsAssessment;
  warnings: string[];
  limits: { queries: number; resultsPerQuery: number; inspectPerRun: number; pagesPerCandidate: number; runsPerDay: number; cacheHours: number };
};
export type DiscoveryCandidate = {
  id: string;
  title: string;
  url: string;
  domain: string;
  searchSnippet: string;
  sourceQueryIndexes: number[];
  discoveredAt: string;
  status: "unverified" | "inspecting" | "related_evidence" | "needs_evidence" | "blocked";
  evidence: Evidence[];
  productEvidence: Array<{ productId: string; relationship: "same_code" | "related_category"; sourceId: string; quote: string }>;
  roleEvidence: Array<{ field: "buyer_role"; sourceId: string; quote: string }>;
  unknowns: string[];
  warnings: string[];
  pagesFetched: number;
  inspectedAt?: string;
  candidateHash?: string;
  savedCompanyId?: string;
  contacts?: Array<{ type: "email" | "phone" | "url"; value: string; role: string; sourceUrl: string; verification: "public_page" }>;
  prescreen?: { priority: "first" | "normal" | "later"; basis: "search_snippet"; reasons: string[] };
  inspectionRuleVersion?: string;
};
export type DiscoveryQuery = {
  query: string;
  status: "pending" | "complete" | "failed";
  resultCount: number;
  durationMs?: number;
  requestId?: string;
  usage?: Record<string, unknown>;
  errorCode?: string;
  message?: string;
  httpStatus?: number;
  providerCode?: string;
  providerMessage?: string;
  retryAfter?: string;
  retryAfterSeconds?: number;
};
export type DiscoveryRun = {
  id: string;
  seedCompanyId: string;
  seedName: string;
  criteria: DiscoveryCriteria;
  planHash: string;
  inputHash: string;
  provider: string;
  status: "searching" | "complete" | "partial" | "failed";
  startedAt: string;
  finishedAt?: string;
  queries: DiscoveryQuery[];
  candidates: DiscoveryCandidate[];
  stats: { returned: number; duplicateDomains: number; seedMatches: number; existingCompanies: number; excluded: number; newCandidates: number };
  inspectionCount: number;
  dataClass: "real";
  modelCalls: 0;
  notice: string;
};
export type DiscoverySearchResult = { run: DiscoveryRun; cached: boolean };
export type DiscoveryInspectResult = { run: DiscoveryRun; candidate: DiscoveryCandidate; cached: boolean };
export type DiscoverySaveResult = { companyId: string; duplicate: boolean; runId: string; candidateId: string };
